// tools/lib/policy/render.mjs: the files and stdout text of `mb policy emit`.
//
// Every renderer is pure and deterministic (no timestamps, no absolute paths), so outputs are golden-tested.
//
// Claude (managed-settings drop-in): key names and value shapes ({source:"github",repo}, {source:"skills-dir"},
// "<p>@<mkt>": bool) match the vendor docs and the strings of Claude Code 2.1.325; enforcement itself was not
// verified live (it needs a root-owned managed-settings dir). Hence the [D] tags.
//
// Codex (requirements.toml): the allowed-source table uses `source = "git"` (vendor doc examples and the
// Codex 0.164 binary strings: MarketplaceAllowedSourceToml with fields source, url, ref, host_pattern; no
// `type`). It is
// not verified live (Codex reads requirements only from /etc/codex, MDM or the cloud bundle), so the file
// carries an UNVERIFIED header (shape not yet verified against a live Codex release).

import { canonical, canonicalPretty, compareCodePoints } from '../../kit/json.mjs';
import { sha256 } from '../hash.mjs';

export const HONESTY = 'Policy is vendored into each plugin; a policy change reaches a user only when that user updates the plugin.';

export const ADVISORY_NOTE = 'Config-file `enforced` values are advisory on a user\'s machine. Real enforcement is CI, repo rules, or host-native policy (these files).';

// [D] = documented by the host vendor, not verified live; [U] = unverified. A tag is dropped only for a
// cell a host test has verified (none yet).
export const GUARANTEE_TABLE = [
  '| Policy | Claude managed | Codex | No host artifact |',
  '|---|---|---|---|',
  '| only this marketplace | enforced `[D]` | enforced `[U]` | advisory |',
  '| plugin enabled when installed | enforced `[D]` | advisory | advisory |',
  '| plugin blocked | enforced `[D]` | advisory | advisory (configurable skills: exit 4) |',
  '| enforced setting | advisory | advisory | advisory |',
].join('\n') + '\n';

export const TAG_LEGEND = '[D] = documented by the host vendor, not verified live; [U] = shape not yet verified against a live Codex release.\n';

const githubSource = (repo) => ({ repo, source: 'github' });

/** marketplaceOnly: false | true | "strict" */
export function claudeDropIn({ mkt, repo, marketplaceOnly, enabled }) {
  const out = {
    enabledPlugins: Object.fromEntries(Object.keys(enabled).sort(compareCodePoints).map((p) => [`${p}@${mkt}`, enabled[p]])),
    extraKnownMarketplaces: { [mkt]: { source: githubSource(repo) } },
  };
  if (marketplaceOnly === true || marketplaceOnly === 'strict') {
    out.strictKnownMarketplaces = [githubSource(repo)];
    if (marketplaceOnly !== 'strict') out.strictKnownMarketplaces.push({ source: 'skills-dir' });
  }
  return canonicalPretty(out);
}

export function codexRequirements({ mkt, repo }) {
  return [
    '# UNVERIFIED shape: [D] learn.chatgpt.com enterprise/managed-configuration; not yet verified against a live Codex release',
    '# Generated by `mb policy emit --host codex`. Do not edit; re-run the emit instead.',
    '# Only the marketplace-source restriction is emitted. See README.txt for the advisory rest.',
    '[marketplaces]',
    'restrict_to_allowed_sources = true',
    '',
    `[marketplaces.allowed_sources.${mkt}]`,
    'source = "git"',
    `url = "https://github.com/${repo}.git"`,
    '',
  ].join('\n');
}

function advisoryLines(decision, { includePlugins }) {
  const lines = [];
  if (includePlugins) {
    const ps = Object.keys(decision.enabled).sort(compareCodePoints);
    if (ps.length) {
      lines.push('Plugin decisions (advisory on Codex: no verified host control):');
      for (const p of ps) lines.push(`  ${p}: ${decision.enabled[p] ? 'required' : 'blocked'} (${decision.reasons[p].join('; ')})`);
    }
  }
  if (decision.settings.length) {
    lines.push(includePlugins
      ? 'Enforced settings (advisory on Codex (no verified host control); the resolver applies them):'
      : 'Enforced settings (advisory: the host does not know them; the resolver applies them):');
    for (const s of decision.settings) {
      lines.push(`  ${s.layer} ${s.plugin ? `plugin ${s.plugin}` : 'all plugins'} ${s.pointer} = ${canonical(s.value)}`);
    }
  }
  if (!lines.length) lines.push('Nothing advisory: every policy in the input is covered by the files here.');
  return lines;
}

export function readme({ host, scope, mkt, repo, marketplaceOnly, decision, files }) {
  const L = [];
  L.push(`mb policy emit: ${host} policy for marketplace "${mkt}" (${scope}), source github ${repo}.`);
  L.push('Generated; do not edit. Re-run `./mb policy emit` after a policy change.');
  L.push('');
  L.push('Files:');
  for (const f of files) L.push(`  ${f}`);
  L.push('  SHA256SUMS  (sha256sum -c SHA256SUMS)');
  L.push('');
  L.push('Delivery:');
  if (host === 'claude') {
    L.push('  Copy managed-settings.d/ next to the managed settings file:');
    L.push('    macOS   /Library/Application Support/ClaudeCode/managed-settings.d/');
    L.push('    Linux   /etc/claude-code/managed-settings.d/');
    L.push('    Windows C:\\Program Files\\ClaudeCode\\managed-settings.d\\');
    L.push('  Drop-ins merge alphabetically after managed-settings.json. Only ONE managed source applies by');
    L.push('  default (server-managed > MDM > files): if you also use server-managed or MDM settings, set');
    L.push('  `managedSourcesBehavior: "merge"` there or put these keys into that source instead.');
    if (marketplaceOnly === false) L.push('  policyEmit.marketplaceOnly is false: no strictKnownMarketplaces allowlist is emitted.');
    if (marketplaceOnly === 'strict') L.push('  policyEmit.marketplaceOnly is "strict": skills-dir plugins (~/.claude/skills) stop loading.');
  } else {
    if (files.includes('requirements.toml')) {
      L.push('  Merge these keys into the system requirements file (one file per machine; do not overwrite');
      L.push('  other requirements already in it):');
      L.push('    Unix    /etc/codex/requirements.toml');
      L.push('    Windows %ProgramData%\\OpenAI\\Codex\\requirements.toml');
      L.push('    macOS MDM  domain com.openai.codex, key requirements_toml_base64');
      L.push('  UNVERIFIED: the shape follows the vendor docs and is not yet verified against a live Codex release.');
    } else {
      L.push('  No requirements.toml: policyEmit.marketplaceOnly is false, and Codex receives only the');
      L.push('  marketplace-source restriction. Everything below is advisory on Codex.');
    }
  }
  L.push('');
  L.push(...advisoryLines(decision, { includePlugins: host === 'codex' }));
  L.push('');
  L.push(ADVISORY_NOTE);
  L.push(HONESTY);
  return L.join('\n') + '\n';
}

/** `sha256sum`-compatible: "<hex>  <path>\n" per file, sorted by path. */
export function sha256sums(fileMap) {
  return Object.keys(fileMap).sort(compareCodePoints).map((rel) => `${sha256(fileMap[rel])}  ${rel}\n`).join('');
}

/**
 * Build every output file for one host. Returns { files: { relPosix: string } } including SHA256SUMS.
 */
export function renderHost({ host, scope, mkt, repo, marketplaceOnly, decision }) {
  const main = {};
  if (host === 'claude') {
    main[`managed-settings.d/50-${mkt}.json`] = claudeDropIn({ mkt, repo, marketplaceOnly, enabled: decision.enabled });
  } else if (marketplaceOnly === true || marketplaceOnly === 'strict') {
    main['requirements.toml'] = codexRequirements({ mkt, repo });
  }
  const files = { ...main };
  files['README.txt'] = readme({ host, scope, mkt, repo, marketplaceOnly, decision, files: [...Object.keys(main).sort(compareCodePoints), 'README.txt'] });
  files.SHA256SUMS = sha256sums(files);
  return files;
}

/** The stdout tail every emit prints: table, legend, then the honesty sentence as the very last line. */
export function guaranteeReport() {
  return '\n' + GUARANTEE_TABLE + TAG_LEGEND + '\n' + ADVISORY_NOTE + '\n' + HONESTY + '\n';
}
