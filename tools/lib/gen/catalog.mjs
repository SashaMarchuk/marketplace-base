// tools/lib/gen/catalog.mjs: README `catalog` and `install` marker bodies and docs/catalog.md.
//
// Org policy status per plugin, from policy/org.json (docs only; the resolver is the real check):
//   blocked   org access.deny matches, org access.allow exists and does not match, or
//             enforced.plugins.<p>.enabled == false
//   required  enforced.plugins.<p>.enabled == true (and not blocked)
//   -         otherwise;  "?" when policy/org.json does not parse (CHK-12 reports it)

import { parse, canonicalPretty } from '../../kit/json.mjs';
import { category } from './marketplaces.mjs';
import { globMatch } from '../policy/decide.mjs';

const cell = (s) => String(s).replace(/\r?\n/g, ' ').replace(/\|/g, '\\|');
const code = (s) => `\`${s}\``;

/** First sentence: up to and including the first ".", "!" or "?" followed by whitespace or the end. */
export function firstSentence(text) {
  const t = String(text ?? '').replace(/\s+/g, ' ').trim();
  const m = /^(.*?[.!?])(\s|$)/.exec(t);
  return m ? m[1] : t;
}

export function policyStatus(repo, name) {
  if (!repo.orgBytes) return '-';
  let org;
  try {
    org = parse(repo.orgBytes, { mode: 'config' });
  } catch {
    return '?';
  }
  if (org === null || typeof org !== 'object' || Array.isArray(org)) return '?';
  const deny = Array.isArray(org.access?.deny) ? org.access.deny : [];
  const allow = Array.isArray(org.access?.allow) ? org.access.allow : null;
  const enabled = org.enforced?.plugins?.[name]?.enabled;
  const blocked = deny.some((p) => typeof p === 'string' && globMatch(p, name))
    || (allow !== null && !allow.some((p) => typeof p === 'string' && globMatch(p, name)))
    || enabled === false;
  if (blocked) return 'blocked';
  return enabled === true ? 'required' : '-';
}

const hostBadge = (p) => (p.hostSpecific.length ? 'host-specific' : '-');

export function catalogBody(repo) {
  if (repo.included.length === 0) {
    return '_No plugins yet. Start with `./mb new skill <plugin>/<skill> "<description>"`._\n';
  }
  const lines = [
    '| Plugin | Skills | Description | Configurable | Host | Org policy |',
    '|---|---|---|---|---|---|',
  ];
  for (const p of repo.included) {
    const skills = p.skills.length ? p.skills.map((s) => code(s.name)).join(', ') : '-';
    lines.push(`| [${p.name}](docs/catalog.md#${p.name}) | ${skills} | ${cell(firstSentence(p.src.description))} | ${p.configurable ? 'yes' : 'no'} | ${hostBadge(p)} | ${policyStatus(repo, p.name)} |`);
  }
  return lines.join('\n') + '\n';
}

export function repoRef(repo) {
  return repo.config.distribution?.repo ?? '<owner>/<repo>';
}

/** README `install`: the example plugin is the first included plugin by name (`<plugin>` if none). */
export function installBody(repo) {
  const r = repoRef(repo), m = repo.mkt;
  const p = repo.included[0]?.name ?? '<plugin>';
  return [
    '**Claude Code**',
    '',
    '```sh',
    `claude plugin marketplace add ${r}`,
    `claude plugin install ${p}@${m}`,
    '```',
    '',
    '**Codex**',
    '',
    '```sh',
    `codex plugin marketplace add ${r}`,
    `codex plugin add ${p}@${m}`,
    '```',
    '',
    '**Plain skills folder** (from a clone of this repo)',
    '',
    '```sh',
    './mb export skills ~/.agents/skills    # Codex',
    './mb export skills ~/.claude/skills    # Claude Code',
    '```',
  ].join('\n') + '\n';
}

/** docs/catalog.md (G): per-plugin detail. versions = Map<name, generated version>. */
export function catalogDoc(repo, versions) {
  const out = [
    '# Catalog',
    '',
    `Plugins of the \`${repo.mkt}\` marketplace. Generated by \`./mb gen\` from each plugin's`,
    '`plugin.src.json`, `SKILL.md` files and `config.defaults.json`. Do not edit.',
  ];
  if (repo.included.length === 0) out.push('', '_No plugins yet._');
  for (const p of repo.included) {
    out.push(
      '',
      `## ${p.name}`,
      '',
      cell(p.src.description),
      '',
      '| Field | Value |',
      '|---|---|',
      `| Version | ${code(versions.get(p.name))} |`,
      `| Source | ${code('./' + p.dir)} |`,
      `| Category | ${cell(category(p, repo))} |`,
      `| Keywords | ${p.src.keywords?.length ? p.src.keywords.map(code).join(', ') : '-'} |`,
      `| Configurable | ${p.configurable ? 'yes' : 'no'} |`,
      `| Host-specific components | ${p.hostSpecific.length ? p.hostSpecific.map(code).join(', ') : '-'} |`,
      `| Org policy | ${policyStatus(repo, p.name)} |`,
      `| Install (Claude Code) | ${code(`claude plugin install ${p.name}@${repo.mkt}`)} |`,
      `| Install (Codex) | ${code(`codex plugin add ${p.name}@${repo.mkt}`)} |`,
      '',
      '### Skills',
      '',
    );
    if (p.skills.length === 0) out.push('_None._');
    else {
      out.push('| Skill | Description |', '|---|---|');
      for (const s of p.skills) out.push(`| ${code(s.name)} | ${cell(s.frontmatter.description ?? '-')} |`);
    }
    if (p.configurable) {
      out.push('', '### Default settings', '', '```json', canonicalPretty(p.defaults).trimEnd(), '```');
    }
  }
  return out.join('\n') + '\n';
}
