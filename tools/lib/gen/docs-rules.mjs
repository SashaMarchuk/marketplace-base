// tools/lib/gen/docs-rules.mjs: docs/base/rules.md (G), generated from tools/lib/rules/CHK-NN.mjs.
// Rule module contract: exports id, severity ('error'|'warning'|'info'), title, fix, slow?.

import fs from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import { compareCodePoints } from '../../kit/json.mjs';

const SEV = { error: 'E', warning: 'W', info: 'I' };
const RULE_FILE = /^CHK-\d\d\.mjs$/;
const cell = (s) => String(s ?? '').replace(/\r?\n/g, ' ').replace(/\|/g, '\\|');
// A fix hint without its own code spans is shown as code, so "<path>" survives markdown rendering.
const hint = (s) => (s && !String(s).includes('`') ? `\`${cell(s)}\`` : cell(s));

/** Import every rule module of rulesDir (missing dir -> []), sorted by id. */
export async function loadRules(rulesDir) {
  let names = [];
  try {
    names = fs.readdirSync(rulesDir).filter((f) => RULE_FILE.test(f)).sort(compareCodePoints);
  } catch (e) {
    if (e.code !== 'ENOENT') throw e;
  }
  const rules = [];
  for (const f of names) {
    const m = await import(pathToFileURL(path.join(rulesDir, f)).href);
    rules.push({ id: m.id ?? f.slice(0, -4), severity: m.severity, title: m.title, fix: m.fix, slow: m.slow === true });
  }
  return rules.sort((a, b) => compareCodePoints(a.id, b.id));
}

export function rulesDoc(rules) {
  const lines = [
    '# `mb check` rules',
    '',
    'Generated by `./mb gen` from `tools/lib/rules/CHK-*.mjs`. Do not edit. Severity: E = error,',
    'W = warning, I = info. Rules marked "slow" are skipped by `./mb check --fast`.',
    '',
    '| ID | Rule | Sev | Fix hint |',
    '|---|---|---|---|',
  ];
  for (const r of rules) {
    const title = cell(r.title) + (r.slow ? ' (slow)' : '');
    lines.push(`| ${r.id} | ${title} | ${SEV[r.severity] ?? cell(r.severity)} | ${hint(r.fix)} |`);
  }
  return lines.join('\n') + '\n';
}
