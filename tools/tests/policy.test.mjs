test('decide(): precedence unit cases', () => {
  const L = (name, doc) => ({ name, doc });
  // enforced false beats nothing; enforced true + deny -> false; org beats team; untouched omitted
  const d = decide(['a', 'b', 'c', 'd'], [
    L('team', { enforced: { plugins: { a: { enabled: true }, b: { enabled: true }, c: { enabled: true } } } }),
    L('org', { access: { deny: ['b'] }, enforced: { plugins: { a: { enabled: false } } } }),
  ]);
  assert.deepEqual(d.enabled, { a: false, b: false, c: true });
  assert.deepEqual(d.unknownPlugins, []);
  // a team allow list also blocks (every layer declaring allow must match)
  assert.deepEqual(decide(['x', 'y'], [L('team', { access: { allow: ['x'] } }), L('org', { access: { allow: ['*'] } })]).enabled, { y: false });
  assert.ok(globMatch('code-*', 'code-review') && !globMatch('code-*', 'xcode-review') && globMatch('*', 'a'));
});

