const TOOLS = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const CMD_DIR = path.join(TOOLS, 'cmd');

const TEMP_DIRS = [];
after(() => { for (const d of TEMP_DIRS) fs.rmSync(d, { recursive: true, force: true }); });

const CONFIG = {
  name: 'acme',
  displayName: 'Acme Skills',
  description: 'Acme test marketplace.',
  owner: { name: 'Alice' },
  distribution: { source: 'github', repo: 'acme/acme-skills' },
  includeExamples: false,
};

const ORG = {
  access: { allow: ['code-*', 'docs-*'], deny: ['legacy-*'] },
  enforced: {
    settings: { checks: { security: true } },
    plugins: { 'code-review': { enabled: true }, ghost: { enabled: true } },
  },
};

const TEAM = {
  enforced: {
    plugins: {
      'code-review': { enabled: false },          // org's `true` wins (org applied last)
      'code-style': { enabled: true, settings: { maxItems: 3 } },
      'legacy-notes': { enabled: true },           // denied by org: a block beats enforced true
    },
  },
};

function write(root, rel, data) {
  const abs = path.join(root, ...rel.split('/'));
  fs.mkdirSync(path.dirname(abs), { recursive: true });
  fs.writeFileSync(abs, typeof data === 'string' ? data : JSON.stringify(data, null, 2) + '\n');
}

function mkRepo({ config = {}, plugins = ['code-review', 'code-style', 'docs-helper', 'legacy-notes'], org = ORG, teams = { payments: TEAM } } = {}) {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'mb-policy-'));
  TEMP_DIRS.push(root);
  write(root, 'marketplace.config.json', { ...CONFIG, ...config });
  for (const p of plugins) write(root, `plugins/${p}/plugin.src.json`, { name: p, version: '0.1.0', description: `The ${p} plugin.` });
  if (org !== null) write(root, 'policy/org.json', org);
  for (const [t, doc] of Object.entries(teams)) write(root, `policy/teams/${t}.json`, doc);
  return root;
}

async function mb(root, argv) {
  let out = '', err = '';
  const code = await main(argv, { root, cmdDir: CMD_DIR, stdout: (t) => { out += t; }, stderr: (t) => { err += t; } });
  return { code, out, err };
}

const readOut = (dir, rel) => fs.readFileSync(path.join(dir, ...rel.split('/')), 'utf8');
const listFiles = (dir) => walk(dir);

function assertSums(dir) {
  const sums = readOut(dir, 'SHA256SUMS');
  const expected = listFiles(dir).filter((f) => f !== 'SHA256SUMS')
    .map((f) => `${crypto.createHash('sha256').update(fs.readFileSync(path.join(dir, ...f.split('/')))).digest('hex')}  ${f}\n`)
    .join('');
  assert.equal(sums, expected);
}

