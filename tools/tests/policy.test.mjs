// ---- MB-POL-001 Claude drop-in ----

test('claude org: golden drop-in, README, SHA256SUMS; table and honesty on stdout', async () => {
  const root = mkRepo({ config: { policyEmit: { marketplaceOnly: true } } });
  const r = await mb(root, ['policy', 'emit', '--host', 'claude']);
  assert.equal(r.code, 0, r.err);
  const dir = path.join(root, 'dist', 'policy', 'claude', 'org');
  assert.deepEqual(listFiles(dir), ['README.txt', 'SHA256SUMS', 'managed-settings.d/50-acme.json']);
  assert.equal(readOut(dir, 'managed-settings.d/50-acme.json'), GOLDEN_CLAUDE_ORG);
  assertSums(dir);
  // enforced.settings is advisory on Claude: listed in README.txt, never in the drop-in.
  assert.match(readOut(dir, 'README.txt'), /org all plugins \/checks\/security = true/);
  assert.doesNotMatch(readOut(dir, 'managed-settings.d/50-acme.json'), /security/);
  // ghost is enforced but not in the catalog: warned, not emitted.
  assert.match(r.err, /enforced\.plugins\.ghost names no plugin in the catalog/);
  // MB-POL-003 + MB-POL-005
  assert.ok(r.out.includes(GUARANTEE_TABLE), 'guarantee table printed');
  assert.match(r.out, /enforced `\[D\]` \| enforced `\[U\]`/);
  assert.ok(r.out.endsWith(HONESTY + '\n'), 'stdout ends with the honesty sentence');
});

