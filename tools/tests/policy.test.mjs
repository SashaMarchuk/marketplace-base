test('--out writes to that dir and removes a stale emit file there; re-run is byte-identical', async () => {
  const root = mkRepo({ config: { policyEmit: { marketplaceOnly: true } } });
  const out = path.join(root, 'custom-out');
  assert.equal((await mb(root, ['policy', 'emit', '--host', 'codex', '--out', out])).code, 0);
  const first = readOut(out, 'SHA256SUMS');
  assert.equal((await mb(root, ['policy', 'emit', '--host', 'codex', '--out', out])).code, 0);
  assert.equal(readOut(out, 'SHA256SUMS'), first);
  // switching marketplaceOnly off must not leave the old requirements.toml behind
  write(root, 'marketplace.config.json', { ...CONFIG, policyEmit: { marketplaceOnly: false } });
  fs.writeFileSync(path.join(out, 'mine.txt'), 'keep');
  assert.equal((await mb(root, ['policy', 'emit', '--host', 'codex', '--out', out])).code, 0);
  assert.deepEqual(listFiles(out), ['README.txt', 'SHA256SUMS', 'mine.txt']);
});

// ---- exit codes ----

test('invalid policy inputs exit 3; usage errors exit 2', async () => {
  const cases = [
    ['lexical (float)', '{ "enforced": { "settings": { "ratio": 0.5 } } }', /POLICY_INVALID/],
    ['duplicate key', '{ "access": {}, "access": {} }', /POLICY_INVALID/],
    ['unknown top key', '{ "enforce": {} }', /POLICY_INVALID/],
    ['unknown key under enforced.plugins.<p>', '{ "enforced": { "plugins": { "a": { "on": true } } } }', /POLICY_INVALID/],
    ['null under enforced', '{ "enforced": { "settings": { "x": null } } }', /ENFORCED_INVALID/],
    ['bad access pattern', '{ "access": { "deny": ["Bad_Name"] } }', /ACCESS_INVALID/],
    ['unknown access key', '{ "access": { "block": ["x"] } }', /ACCESS_INVALID/],
  ];
  for (const [label, text, re] of cases) {
    const root = mkRepo({ org: null, teams: {} });
    write(root, 'policy/org.json', text);
    const r = await mb(root, ['policy', 'emit', '--host', 'claude']);
    assert.equal(r.code, 3, `${label}: ${r.err}`);
    assert.match(r.err, re, label);
    assert.equal(fs.existsSync(path.join(root, 'dist')), false, `${label}: nothing written`);
  }
  // an invalid team file fails too, and an unknown team
  const root = mkRepo({ teams: { ops: '{ "enforced": { "plugins": { "a": null } } }' } });
  assert.equal((await mb(root, ['policy', 'emit', '--host', 'claude', '--team', 'ops'])).code, 3);
  const unk = await mb(root, ['policy', 'emit', '--host', 'claude', '--team', 'nope']);
  assert.equal(unk.code, 3);
  assert.match(unk.err, /TEAM_UNKNOWN/);
  // missing distribution
  const nd = mkRepo();
  const cfg = { ...CONFIG }; delete cfg.distribution;
  write(nd, 'marketplace.config.json', cfg);
  assert.equal((await mb(nd, ['policy', 'emit', '--host', 'claude'])).code, 3);
  // usage
  for (const argv of [['policy'], ['policy', 'emit'], ['policy', 'emit', '--host', 'vscode'], ['policy', 'push', '--host', 'claude'],
    ['policy', 'emit', '--host', 'claude', '--team', 'Bad_Team'], ['policy', 'emit', 'x', '--host', 'claude']]) {
    assert.equal((await mb(root, argv)).code, 2, argv.join(' '));
  }
});

